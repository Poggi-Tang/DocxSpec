"""Compile a Studio model through DocxSpec; no arbitrary user templates execute."""

import io
import tempfile
from copy import deepcopy
from pathlib import Path

from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm
from model import DEFAULT_TEXTS, image_bytes, validate
from PIL import Image

from docxspec import (
    CellStyle,
    TableStyle,
    TextStyle,
    WordAPI,
    mark_update_fields_on_open,
    refresh_docx_fields,
)
from docxspec._section_templates import assemble_ds_front_matter, load_ds_section
from docxspec.kl_standard import replace_cover_title


def render_docx(model, *, refresh_fields=False):
    model = validate(model)
    with tempfile.TemporaryDirectory(prefix="docxspec-studio-") as tmp:
        root = Path(tmp)
        template = load_ds_section("body")
        sample_table_properties = deepcopy(template.tables[-1]._tbl.tblPr)
        section = template.sections[-1]
        content_width = (section.page_width - section.left_margin - section.right_margin) / 360000
        template.element.body.clear_content()
        metadata = model.get("section_meta")
        cover_text = model["texts"].get("0", DEFAULT_TEXTS[0])
        template.add_paragraph("{{p report}}", style="DS正文")
        template.core_properties.author = "DocxSpec"
        template.core_properties.title = "测试报告"
        template.core_properties.last_modified_by = "DocxSpec"
        template.core_properties.comments = "Generated by DocxSpec Studio"
        template.save(root / "template.docx")
        api = WordAPI(str(root / "template.docx"))
        body = api.new_container()
        normal = TextStyle(style_name="DS正文")
        for n, title in enumerate(model["sections"]):
            entry = metadata[n] if metadata else dict(
                kind="cover" if n == 0 else ("cases" if n == 2 else "heading"), level=1
            )
            if entry["kind"] not in ("heading", "cases"):
                continue  # These front pages are retained directly from the master.
            level = entry["level"]
            if level == 1 and n > (5 if metadata else 1):
                body.add_page_break()
            # Use the actual hierarchy read from the master; Word supplies numbering.
            style_name = f"DS{'一二三四五六'[level - 1]}级标题"
            body.add_heading(title, style=TextStyle(style_name=style_name))
            if entry["kind"] != "cases":
                body.add_paragraph(
                    model["texts"].get(
                        str(n),
                        "" if metadata else (
                            DEFAULT_TEXTS[n] if n < len(DEFAULT_TEXTS) else "点击此处编写章节内容。"
                        ),
                    ),
                    style=normal,
                )
                continue
            body.add_paragraph(model["intro"], style=normal)
            records = [
                (i, c)
                for i, c in enumerate(model["cases"])
                if model["source"] != "失败用例" or c["result"] == "失败"
            ]
            if model["repeat"] == "仅首条记录":
                records = records[:1]
            if not records and model["empty"] == "显示待补充":
                body.add_paragraph("测试数据待补充", style=normal)
            for i, c in records:
                f = model["format"].get(str(i), {})
                # No format entry means exact inheritance from the master, including fonts.
                overrides = {}
                if "size" in f:
                    overrides["font_size"] = f["size"] * 0.75
                if "line" in f:
                    overrides["line_spacing"] = float(f["line"])
                if "bold" in f:
                    overrides["bold"] = f["bold"]
                if "italic" in f:
                    overrides["italic"] = f["italic"]
                if "center" in f:
                    overrides["align"] = "center" if f["center"] else "left"
                header_style = CellStyle(paragraph_style_name="DS表格表头", **overrides)
                cell_style = CellStyle(
                    paragraph_style_name=f.get("style", "DS表格文字"), **overrides
                )
                case_title = f"{c['id']}　{c['name']}"
                if metadata and level == 6:
                    body.add_paragraph(case_title, style=normal)
                else:
                    case_level = level + 1
                    body.add_heading(
                        case_title, level=case_level,
                        style=TextStyle(style_name=f"DS{'一二三四五六'[case_level - 1]}级标题"),
                    )
                body.add_table_caption_auto(c["name"], reset_sequence=(i == records[0][0]))
                rows = [
                    ["测试步骤", "\n".join(f"{j + 1}. {s}" for j, s in enumerate(c["steps"]))],
                    ["预期结果", c["expected"]],
                    ["实际结果", c["actual"]],
                    ["测试结论", c["result"]],
                    ["截图", "未提供截图"],
                ]
                # Use explicit text parts, so user strings never become local file paths.
                data = [[{"text": v} for v in row] for row in rows]
                table = api.insert_table(
                    body.subdoc,
                    data,
                    header_style=header_style,
                    body_style=cell_style,
                    table_style=TableStyle(
                        col_widths_cm=[3, content_width - 3], header_rows=0
                    ),
                )
                # Copy the master's table borders, margins and table style, not a new design.
                properties = deepcopy(sample_table_properties)
                table._tbl.replace(table._tbl.tblPr, properties)
                for row in table.rows:
                    row.cells[0].paragraphs[0].style = "DS表格表头"
                    if "color" in f:
                        shade = OxmlElement("w:shd")
                        shade.set(qn("w:fill"), f["color"][1:])
                        row.cells[0]._tc.get_or_add_tcPr().append(shade)
                if c.get("image"):
                    with Image.open(io.BytesIO(image_bytes(c["image"]))) as image:
                        image = image.convert("RGB")
                        width, height = image.size
                        stream = io.BytesIO()
                        image.save(stream, format="PNG")
                        stream.seek(0)
                    cell = table.cell(4, 1)
                    cell.text = ""
                    cell.paragraphs[0].style = "DS图片"
                    scale = min((content_width - 3 - 0.4) / width, 10 / height)
                    cell.paragraphs[0].add_run().add_picture(
                        stream, width=Cm(width * scale), height=Cm(height * scale)
                    )
                    body.add_figure_caption_auto(
                        c["name"] + "截图",
                        reset_sequence=not any(
                            earlier.get("image") for earlier_index, earlier in records
                            if earlier_index < i
                        ),
                    )
                # Keep a normal-sized case table together; oversized tables can still flow.
                for row_index, row in enumerate(table.rows):
                    row._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
                    for cell in row.cells:
                        for paragraph in cell.paragraphs:
                            paragraph.paragraph_format.keep_with_next = (
                                row_index < len(table.rows) - 1
                            )
        output = root / "report.docx"
        api.render({"report": body.subdoc}, str(output))
        document = Document(output)
        assemble_ds_front_matter(document, prepare_cover=lambda cover: replace_cover_title(cover, cover_text))
        document.save(output)
        if refresh_fields:
            refresh_docx_fields(output, use_word=True, raise_on_word_error=True)
        else:
            mark_update_fields_on_open(output)
        return output.read_bytes()
