"""Compile a Studio model through DocxSpec; no arbitrary user templates execute."""

import io
import tempfile
from pathlib import Path

from docx import Document
from docx.enum.style import WD_STYLE_TYPE
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt
from model import DEFAULT_TEXTS, image_bytes, validate
from PIL import Image

from docxspec import CellStyle, TableStyle, TextStyle, WordAPI, mark_update_fields_on_open


def render_docx(model):
    model = validate(model)
    with tempfile.TemporaryDirectory(prefix="docxspec-studio-") as tmp:
        root = Path(tmp)
        template = Document()
        section = template.sections[0]
        section.page_width, section.page_height = Cm(21), Cm(29.7)
        section.top_margin = section.bottom_margin = Cm(2)
        section.left_margin = section.right_margin = Cm(2.5)
        for name, size, bold in [
            ("DS正文", 11.25, False),
            ("DS一级标题", 20, True),
            ("DS二级标题", 16, True),
            ("DS表格文字", 11.25, False),
        ]:
            style = template.styles.add_style(name, WD_STYLE_TYPE.PARAGRAPH)
            style.font.name = "Noto Serif CJK SC"
            style.font.size = Pt(size)
            style.font.bold = bold
            style.element.get_or_add_rPr().get_or_add_rFonts().set(
                qn("w:eastAsia"), "Noto Serif CJK SC"
            )
            style.paragraph_format.space_after = Pt(8)
            if "标题" in name:
                style.paragraph_format.keep_with_next = True
        template.core_properties.author = "DocxSpec"
        template.core_properties.title = "测试报告"
        template.core_properties.last_modified_by = "DocxSpec"
        template.core_properties.comments = "Generated by DocxSpec Studio"
        template.add_paragraph("{{p report}}")
        template.save(root / "template.docx")
        api = WordAPI(str(root / "template.docx"))
        body = api.new_container()
        normal = TextStyle(style_name="DS正文", font_name="Noto Serif CJK SC", font_size=11.25)
        for n, title in enumerate(model["sections"]):
            if n:
                body.add_page_break()
            body.add_heading(f"{n + 1}　{title}", style=TextStyle(style_name="DS一级标题"))
            if n != 2:
                body.add_paragraph(
                    model["texts"].get(
                        str(n),
                        DEFAULT_TEXTS[n] if n < len(DEFAULT_TEXTS) else "点击此处编写章节内容。",
                    ),
                    style=normal,
                )
                continue
            body.add_paragraph(model["intro"], style=normal)
            records = [
                (i, c)
                for i, c in enumerate(model["cases"])
                if model["source"] != "失败用例" or c["result"] == "失败"
            ]
            if model["repeat"] == "仅首条记录":
                records = records[:1]
            if not records and model["empty"] == "显示待补充":
                body.add_paragraph("测试数据待补充", style=normal)
            for i, c in records:
                f = dict(
                    size=15,
                    line="1.65",
                    color="#f2f4f8",
                    style="DS正文",
                    bold=False,
                    italic=False,
                    center=False,
                )
                f.update(model["format"].get(str(i), {}))
                # Browser sizes are CSS pixels; Word sizes use points.
                cell_style = CellStyle(
                    paragraph_style_name=f["style"],
                    font_name="Noto Serif CJK SC",
                    font_size=f["size"] * 0.75,
                    bold=f["bold"] or f["style"] == "DS一级标题",
                    italic=f["italic"],
                    align="center" if f["center"] else "left",
                    line_spacing=float(f["line"]),
                )
                body.add_heading(
                    f"{c['id']}　{c['name']}", level=2, style=TextStyle(style_name="DS二级标题")
                )
                rows = [
                    ["测试步骤", "\n".join(f"{j + 1}. {s}" for j, s in enumerate(c["steps"]))],
                    ["预期结果", c["expected"]],
                    ["实际结果", c["actual"]],
                    ["测试结论", c["result"]],
                    ["截图", "未提供截图"],
                ]
                # Use explicit text parts, so user strings never become local file paths.
                data = [[{"text": v} for v in row] for row in rows]
                table = api.insert_table(
                    body.subdoc,
                    data,
                    header_style=cell_style,
                    body_style=cell_style,
                    table_style=TableStyle(
                        col_widths_cm=[3, 13], header_rows=0, border_color="9CA6B8"
                    ),
                )
                for row in table.rows:
                    shade = OxmlElement("w:shd")
                    shade.set(qn("w:fill"), f["color"][1:])
                    row.cells[0]._tc.get_or_add_tcPr().append(shade)
                    for run in row.cells[0].paragraphs[0].runs:
                        run.bold = True
                if c.get("image"):
                    with Image.open(io.BytesIO(image_bytes(c["image"]))) as image:
                        image = image.convert("RGB")
                        width, height = image.size
                        stream = io.BytesIO()
                        image.save(stream, format="PNG")
                        stream.seek(0)
                    cell = table.cell(4, 1)
                    cell.text = ""
                    scale = min(12 / width, 10 / height)
                    cell.paragraphs[0].add_run().add_picture(
                        stream, width=Cm(width * scale), height=Cm(height * scale)
                    )
                # Keep a normal-sized case table together; oversized tables can still flow.
                for row_index, row in enumerate(table.rows):
                    row._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
                    for cell in row.cells:
                        for paragraph in cell.paragraphs:
                            paragraph.paragraph_format.keep_with_next = (
                                row_index < len(table.rows) - 1
                            )
                            paragraph.paragraph_format.space_after = Pt(3)
        output = root / "report.docx"
        api.render({"report": body.subdoc}, str(output))
        mark_update_fields_on_open(output)
        return output.read_bytes()
